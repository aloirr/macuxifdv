// Testes da trava do deploy por issue (ADR 0046). node --test scripts/ci/*.test.mjs
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import {
  AUTOR_ISSUE, MAX_COMMITS, corpoDaIssue, decidirComentario, erroDaTrava, lerMarcador, marcador, textoAprova,
  tituloDaIssue, versaoDoTitulo,
} from './producao-trava.mjs';

const SHA = '839a082'.padEnd(40, '0');
const OUTRO = 'abcdef1'.padEnd(40, '0');
const ler = (p) => readFileSync(new URL(`../../${p}`, import.meta.url), 'utf8');
const RODAPE = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

const issueAberta = (extra = {}) => ({
  number: 250,
  title: 'Aprovar deploy v1.0.8',
  state: 'open',
  labels: [{ name: 'trava-deploy' }],
  user: { login: AUTOR_ISSUE },
  body: `${marcador('v1.0.8', SHA)}\n**Versão:** \`v1.0.8\``,
  ...extra,
});
const evento = ({ issue = {}, autor = 'aloirr', texto = 'aprovado v1.0.8', action = 'created' } = {}) => ({
  action,
  issue: issueAberta(issue),
  comment: { user: { login: autor }, body: texto },
});

test('título e marcador: só "Aprovar deploy vX.Y.Z" e SHA de 40 hex', () => {
  assert.equal(tituloDaIssue('v1.0.8'), 'Aprovar deploy v1.0.8');
  assert.equal(versaoDoTitulo('Aprovar deploy v1.0.8'), 'v1.0.8');
  for (const t of ['Aprovar deploy 1.0.8', 'Aprovar deploy v1.0.8 ', 'aprovar deploy v1.0.8', 'Aprovar deploy v1.0', ''])
    assert.equal(versaoDoTitulo(t), null, t);
  assert.deepEqual(lerMarcador(`x\n${marcador('v1.0.8', SHA)}\ny`), { versao: 'v1.0.8', sha: SHA });
  assert.equal(lerMarcador('<!-- trava-deploy versao=v1.0.8 sha=839a082 -->'), null);
});

test('texto: uma linha "aprovado vX.Y.Z" aprova; negação, citação e outra versão não', () => {
  for (const t of ['aprovado v1.0.8', 'Aprovado v1.0.8.', '**aprovado v1.0.8**', '  aprovado   v1.0.8 !', `aprovado v1.0.8${RODAPE}`,
    'ok, segue:\r\naprovado v1.0.8\r\n'])
    assert.equal(textoAprova(t, 'v1.0.8'), true, t);
  for (const t of ['não aprovado v1.0.8', '> aprovado v1.0.8', 'aprovado v1.0.9', 'aprovado v1.0.80', 'aprovado', 'aprovo v1.0.8',
    'aprovado v1.0.8 amanhã', 'v1.0.8', '', RODAPE])
    assert.equal(textoAprova(t, 'v1.0.8'), false, t);
  assert.equal(textoAprova('aprovado v1.0.8', 'v1.0'), false);
});

test('comentário: aprova só com rótulo, issue aberta do bot, autor aloirr e a versão do título', () => {
  assert.deepEqual(decidirComentario(evento()), { aprovar: true, versao: 'v1.0.8', sha: SHA, issue: 250 });
  assert.equal(decidirComentario(evento({ autor: 'AloirR' })).aprovar, true, 'login sem diferenciar maiúsculas');
});

test('comentário: aceita o rodapé de atribuição "Generated by Claude Code"', () => {
  assert.equal(decidirComentario(evento({ texto: `aprovado v1.0.8${RODAPE}` })).aprovar, true);
});

test('comentário: recusa autor errado, versão errada, texto sem "aprovado", sem rótulo, fechada e o resto', () => {
  const casos = [
    [evento({ autor: 'github-actions[bot]' }), /autor/],
    [evento({ autor: 'outra-pessoa' }), /autor/],
    [evento({ texto: 'aprovado v1.0.9' }), /aprovado v1\.0\.8/],
    [evento({ texto: 'pode seguir com a v1.0.8' }), /aprovado v1\.0\.8/],
    [evento({ texto: `não aprovado v1.0.8${RODAPE}` }), /aprovado v1\.0\.8/],
    [evento({ issue: { labels: [{ name: 'bug' }] } }), /rótulo/],
    [evento({ issue: { labels: [] } }), /rótulo/],
    [evento({ issue: { state: 'closed' } }), /fechada/],
    [evento({ issue: { pull_request: { url: 'x' } } }), /PR/],
    [evento({ issue: { user: { login: 'aloirr' } } }), /aberta por/],
    [evento({ issue: { title: 'Aprovar deploy v1.0' } }), /título/],
    [evento({ issue: { body: 'sem marcador' } }), /marcador/],
    [evento({ issue: { body: marcador('v1.0.9', SHA) } }), /marcador/],
    [evento({ action: 'edited' }), /ação/],
    [{ action: 'created' }, /sem issue/],
  ];
  for (const [e, motivo] of casos) {
    const d = decidirComentario(e);
    assert.equal(d.aprovar, false, JSON.stringify(e.comment ?? e));
    assert.match(d.motivo, motivo);
  }
});

const aprovada = (extra = {}) => issueAberta({ state: 'closed', state_reason: 'completed', labels: [{ name: 'trava-deploy' }, { name: 'aprovado' }], ...extra });
const comAprovacao = () => [{ user: { login: 'github-actions[bot]' }, body: 'Aprovado. Tag ...' }, { user: { login: 'aloirr' }, body: `aprovado v1.0.8${RODAPE}` }];

test('publicar: a tag passa só com a issue aprovada do mesmo commit (re-run de tag aprovada continua valendo)', () => {
  const base = { versao: 'v1.0.8', sha: SHA, comentariosDe: () => comAprovacao() };
  assert.equal(erroDaTrava({ ...base, issues: [aprovada()] }), null);
  // uma issue recusada (fechada sem aprovar) e outra aprovada: vale a aprovada
  assert.equal(erroDaTrava({ ...base, issues: [aprovada({ number: 249, state_reason: 'not_planned', labels: [{ name: 'trava-deploy' }] }), aprovada()] }), null);
});

test('publicar: recusa tag sem issue, issue aberta, sem rótulo aprovado, outro commit, sem o comentário do aloirr', () => {
  const base = { versao: 'v1.0.8', sha: SHA, comentariosDe: () => comAprovacao() };
  assert.match(erroDaTrava({ ...base, issues: [] }), /não tem a issue/);
  assert.match(erroDaTrava({ ...base, issues: [aprovada({ title: 'Aprovar deploy v1.0.9' })] }), /não tem a issue/);
  assert.match(erroDaTrava({ ...base, issues: [aprovada({ labels: [{ name: 'aprovado' }] })] }), /não tem a issue/);
  assert.match(erroDaTrava({ ...base, issues: [issueAberta()] }), /concluída/);
  assert.match(erroDaTrava({ ...base, issues: [aprovada({ state_reason: 'not_planned' })] }), /concluída/);
  assert.match(erroDaTrava({ ...base, issues: [aprovada({ labels: [{ name: 'trava-deploy' }] })] }), /rótulo aprovado/);
  assert.match(erroDaTrava({ ...base, issues: [aprovada({ user: { login: 'aloirr' } })] }), /liberar versão/);
  assert.match(erroDaTrava({ ...base, sha: OUTRO, issues: [aprovada()] }), /outro commit/);
  assert.match(erroDaTrava({ ...base, comentariosDe: () => [{ user: { login: 'outra-pessoa' }, body: 'aprovado v1.0.8' }], issues: [aprovada()] }), /comentário/);
  assert.match(erroDaTrava({ ...base, comentariosDe: () => [{ user: { login: 'aloirr' }, body: 'aprovado v1.0.9' }], issues: [aprovada()] }), /comentário/);
  assert.match(erroDaTrava({ ...base, sha: 'abc', issues: [aprovada()] }), /SHA inválido/);
});

test('corpo da issue: marcador, SHA, link do run, frase de aprovação, PRs e commits sem menção', () => {
  const commits = [
    { sha: SHA, assunto: 'Produção: liberar (#241)' },
    { sha: OUTRO, assunto: 'Ajuste pedido por @alguem (#240)' },
  ];
  const corpo = corpoDaIssue({ versao: 'v1.0.8', sha: SHA, run: 'https://github.com/o/r/actions/runs/1', anterior: 'v1.0.7', commits });
  assert.deepEqual(lerMarcador(corpo), { versao: 'v1.0.8', sha: SHA });
  assert.match(corpo, new RegExp(SHA));
  assert.match(corpo, /actions\/runs\/1/);
  assert.match(corpo, /`aprovado v1\.0\.8`/);
  assert.match(corpo, /Desde `v1\.0\.7` \(2 commit\(s\)\)/);
  assert.match(corpo, /PRs: #240, #241/);
  assert.match(corpo, /- `839a082` Produção: liberar \(#241\)/);
  assert.doesNotMatch(corpo, /@alguem/, 'commit não notifica ninguém');
  const muitos = Array.from({ length: MAX_COMMITS + 3 }, (_, i) => ({ sha: SHA, assunto: `c${i}` }));
  assert.match(corpoDaIssue({ versao: 'v1.0.8', sha: SHA, run: 'r', anterior: '', commits: muitos }), /e mais 3 commit/);
});

/** Conteúdo dos blocos `run:` (linha única ou bloco `|`). */
function blocosRun(yaml) {
  const linhas = yaml.split('\n');
  const out = [];
  linhas.forEach((l, i) => {
    const m = /^(\s*)(?:- )?run: ?(.*)$/.exec(l);
    if (!m) return;
    if (m[2] !== '|') return out.push(m[2]);
    const ind = m[1].length;
    for (let j = i + 1; j < linhas.length && (linhas[j].trim() === '' || linhas[j].search(/\S/) > ind); j++) out.push(linhas[j]);
  });
  return out;
}

test('workflows da trava: permissões mínimas por job, filtro barato no aprovar e nada do evento no shell', () => {
  const lib = ler('.github/workflows/producao-liberar.yml');
  const apr = ler('.github/workflows/producao-aprovar.yml');
  const pub = ler('.github/workflows/producao-publicar.yml');
  for (const wf of [lib, apr, pub]) {
    assert.match(wf, /^permissions: \{\}$/m, 'sem permissão no topo');
    for (const l of blocosRun(wf)) assert.doesNotMatch(l, /\$\{\{/, `interpolação no shell: ${l.trim()}`);
  }
  assert.match(lib, /producao-trava\.mjs abrir/);
  assert.match(apr, /^ {2}issue_comment:\n {4}types: \[created\]$/m);
  for (const c of ["github.event.issue.pull_request == null", "github.event.issue.state == 'open'",
    "contains(github.event.issue.labels.*.name, 'trava-deploy')", "github.event.comment.user.login == 'aloirr'"])
    assert.ok(apr.includes(c), c);
  assert.match(apr, /producao-trava\.mjs comentario/);
  assert.match(apr, /state_reason=completed/);
  assert.match(apr, /labels\[\]=aprovado/);
  // fecha a issue antes de disparar o publicar (o publicar confere a issue aprovada)
  assert.ok(apr.indexOf('state_reason=completed') < apr.indexOf('gh workflow run producao-publicar.yml'));
  assert.match(pub, /producao-trava\.mjs publicar/);
  assert.match(pub, /issues: read/);
  assert.ok(pub.indexOf('producao-trava.mjs publicar') < pub.indexOf('name: PRODUCAO'), 'a trava vem antes do deploy');
  assert.doesNotMatch(apr, /environment:|secrets\.(?!GITHUB_TOKEN)/, 'sem secret novo nem PRODUCAO no aprovar');
  assert.doesNotMatch(lib, /secrets\.(?!GITHUB_TOKEN)/);
});
