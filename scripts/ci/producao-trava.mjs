#!/usr/bin/env node
/**
 * Trava do deploy de PRODUÇÃO por issue (ADR 0046). O plano do repositório privado não tem "Required reviewers": o
 * environment PRODUCAO não para (a v1.0.7 subiu sem aprovação). A trava passa a ser uma issue que só o Alexandre (conta
 * `aloirr`, pelo chat e pela ponte) aprova com um comentário. Sem dependência: node:child_process e node:fs.
 *
 *   producao-liberar.yml  — conferências de hoje e `abrir`: abre a issue "Aprovar deploy vX.Y.Z" (rótulo trava-deploy,
 *                           SHA, link do run, commits e PRs desde a última tag v*). Não cria tag nem dispara deploy.
 *   producao-aprovar.yml  — issue_comment: `comentario` decide se o comentário aprova (rótulo, issue aberta e do bot,
 *                           autor aloirr, linha "aprovado vX.Y.Z" com a versão do título); depois a mesma conferência do
 *                           producao-conferir.mjs, a tag, o rótulo aprovado, o fechamento e o disparo do publicar na tag.
 *   producao-publicar.yml — `publicar`: a tag só publica com a issue dela aprovada (fechada como concluída, rótulo
 *                           aprovado, aberta pelo bot, SHA do marcador = commit da tag e o comentário de aprovação do
 *                           aloirr). O "Re-run all jobs" de uma tag já aprovada passa de novo (a issue continua aprovada).
 *
 * Modos (tudo por variável de ambiente ou pelo arquivo do evento; nada interpolado no shell):
 *   abrir      VERSAO, SHA, GITHUB_REPOSITORY, GITHUB_SERVER_URL, GITHUB_RUN_ID, GH_TOKEN (checkout com fetch-depth 0).
 *   comentario GITHUB_EVENT_PATH → escreve aprovar=true|false, versao, sha e issue em $GITHUB_OUTPUT. Comentário que não
 *              aprova só deixa o motivo no log (nada é comentado na issue).
 *   publicar   VERSAO, SHA, GITHUB_REPOSITORY, GH_TOKEN.
 * Saída: 0 = ok (no `comentario`, também quando o comentário não aprova); 1 = conferência falhou; 2 = erro de uso.
 */
import { execFileSync } from 'node:child_process';
import { appendFileSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SHA_COMPLETO, VERSAO_LIBERAR } from './producao-conferir.mjs';

export const ROTULO_TRAVA = 'trava-deploy';
export const ROTULO_APROVADO = 'aprovado';
export const APROVADOR = 'aloirr';
export const AUTOR_ISSUE = 'github-actions[bot]';
export const MAX_COMMITS = 200;

export const tituloDaIssue = (versao) => `Aprovar deploy ${versao}`;

/** Versão do título "Aprovar deploy vX.Y.Z" (null se o título não é de trava). */
export function versaoDoTitulo(titulo) {
  const m = /^Aprovar deploy (v\S+)$/.exec(String(titulo || ''));
  return m && VERSAO_LIBERAR.test(m[1]) ? m[1] : null;
}

/** Marcador invisível no corpo da issue: o SHA que a aprovação libera. */
export const marcador = (versao, sha) => `<!-- ${ROTULO_TRAVA} versao=${versao} sha=${sha} -->`;

export function lerMarcador(corpo) {
  const m = new RegExp(`<!-- ${ROTULO_TRAVA} versao=(\\S+) sha=([0-9a-f]{40}) -->`).exec(String(corpo || ''));
  return m ? { versao: m[1], sha: m[2] } : null;
}

const nomesDosRotulos = (issue) => (Array.isArray(issue?.labels) ? issue.labels : []).map((l) => (typeof l === 'string' ? l : l?.name));
const login = (u) => String(u?.login || '').toLowerCase();

/**
 * O texto aprova a versão? Precisa de UMA LINHA que seja exatamente "aprovado vX.Y.Z" (sem diferenciar maiúsculas; aceita
 * negrito/itálico/crase e ponto final). Assim "não aprovado v1.0.8" e a citação "> aprovado v1.0.8" não aprovam, e o
 * rodapé de atribuição ("---", "_Generated by [Claude Code](...)_") nas outras linhas não atrapalha.
 */
export function textoAprova(texto, versao) {
  if (!VERSAO_LIBERAR.test(String(versao || ''))) return false;
  const alvo = `aprovado ${versao}`.toLowerCase();
  return String(texto || '')
    .split(/\r?\n/)
    .some((linha) => linha.replace(/[*_`]/g, '').replace(/[.!\s]+$/, '').trim().replace(/\s+/g, ' ').toLowerCase() === alvo);
}

/**
 * Decisão do producao-aprovar.yml sobre o evento issue_comment (função pura).
 * @returns {{aprovar: true, versao: string, sha: string, issue: number} | {aprovar: false, motivo: string}}
 */
export function decidirComentario(evento, aprovador = APROVADOR) {
  const issue = evento?.issue;
  const comentario = evento?.comment;
  const nao = (motivo) => ({ aprovar: false, motivo });
  if (evento?.action !== 'created') return nao(`ação ${evento?.action || '?'} (só comentário novo)`);
  if (!issue || !comentario) return nao('evento sem issue ou comentário');
  if (issue.pull_request) return nao('comentário em PR');
  if (!nomesDosRotulos(issue).includes(ROTULO_TRAVA)) return nao(`issue sem o rótulo ${ROTULO_TRAVA}`);
  if (issue.state !== 'open') return nao('issue fechada');
  if (login(issue.user) !== AUTOR_ISSUE) return nao(`issue aberta por ${issue.user?.login || '?'} (só a do "producao — liberar versão")`);
  if (login(comentario.user) !== aprovador.toLowerCase()) return nao(`autor ${comentario.user?.login || '?'} não aprova`);
  const versao = versaoDoTitulo(issue.title);
  if (!versao) return nao('título fora do padrão "Aprovar deploy vX.Y.Z"');
  const alvo = lerMarcador(issue.body);
  if (!alvo || alvo.versao !== versao || !SHA_COMPLETO.test(alvo.sha)) return nao('marcador da issue ausente ou diferente do título');
  if (!textoAprova(comentario.body, versao)) return nao(`o comentário não tem a linha "aprovado ${versao}"`);
  return { aprovar: true, versao, sha: alvo.sha, issue: Number(issue.number) };
}

/** Por que esta issue não aprova a tag (null = aprova). Função pura; `comentarios` são os da issue. */
export function erroDaIssue(issue, comentarios, { versao, sha }, aprovador = APROVADOR) {
  const rotulos = nomesDosRotulos(issue);
  if (issue.state !== 'closed' || issue.state_reason !== 'completed') return `a issue #${issue.number} não foi fechada como concluída`;
  if (!rotulos.includes(ROTULO_APROVADO)) return `a issue #${issue.number} não tem o rótulo ${ROTULO_APROVADO}`;
  if (login(issue.user) !== AUTOR_ISSUE) return `a issue #${issue.number} não foi aberta pelo "producao — liberar versão"`;
  const alvo = lerMarcador(issue.body);
  if (!alvo || alvo.versao !== versao || alvo.sha !== sha) return `a issue #${issue.number} aprova outro commit (a tag ${versao} aponta para ${sha})`;
  const ok = (Array.isArray(comentarios) ? comentarios : []).some(
    (c) => login(c?.user) === aprovador.toLowerCase() && textoAprova(c?.body, versao),
  );
  return ok ? null : `a issue #${issue.number} não tem o comentário "aprovado ${versao}" de ${aprovador}`;
}

/**
 * A tag pode publicar? Precisa de uma issue de trava da versão aprovada (função pura).
 * @param {object[]} issues  issues com o rótulo trava-deploy (qualquer estado)
 * @param {(numero: number) => object[]} comentariosDe
 */
export function erroDaTrava({ versao, sha, issues, comentariosDe }) {
  if (!SHA_COMPLETO.test(String(sha || ''))) return `SHA inválido: "${sha}"`;
  const candidatas = (Array.isArray(issues) ? issues : []).filter(
    (i) => i && !i.pull_request && i.title === tituloDaIssue(versao) && nomesDosRotulos(i).includes(ROTULO_TRAVA),
  );
  if (!candidatas.length)
    return `a tag ${versao} não tem a issue "${tituloDaIssue(versao)}" (rótulo ${ROTULO_TRAVA}): libere pelo "producao — liberar versão" e aprove na issue`;
  const erros = candidatas.map((i) => erroDaIssue(i, comentariosDe(i.number), { versao, sha }));
  return erros.includes(null) ? null : `deploy de ${versao} não aprovado: ${erros.join('; ')}`;
}

/** Corpo da issue de trava (função pura). Commits: [{sha, assunto}] do mais novo ao mais antigo. */
export function corpoDaIssue({ versao, sha, run, anterior, commits }) {
  const lista = Array.isArray(commits) ? commits : [];
  const semMencao = (s) => String(s).replace(/@/g, '@​');
  const prs = [...new Set(lista.flatMap((c) => [...String(c.assunto).matchAll(/\(#(\d+)\)/g)].map((m) => Number(m[1]))))].sort((a, b) => a - b);
  const linhas = [
    marcador(versao, sha),
    `**Versão:** \`${versao}\``,
    `**Commit:** \`${sha}\``,
    `**Conferência:** ${run} (commit no main, CI verde e imagem da API no GHCR)`,
    '',
    `Para aprovar, comente nesta issue exatamente: \`aprovado ${versao}\``,
    'A aprovação confere tudo de novo, cria a tag, dispara o "producao — publicar" e fecha a issue. Para recusar, feche a issue sem comentar.',
    '',
    `### Desde ${anterior ? `\`${anterior}\`` : 'o início'} (${lista.length} commit(s))`,
  ];
  if (prs.length) linhas.push('', `PRs: ${prs.map((n) => `#${n}`).join(', ')}`);
  linhas.push('');
  for (const c of lista.slice(0, MAX_COMMITS)) linhas.push(`- \`${String(c.sha).slice(0, 7)}\` ${semMencao(c.assunto)}`);
  if (lista.length > MAX_COMMITS) linhas.push(`- … e mais ${lista.length - MAX_COMMITS} commit(s)`);
  return `${linhas.join('\n')}\n`;
}

const executar = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
const linhasJson = (saida) => String(saida).split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l));
const issuesDaTrava = (repo, estado) =>
  linhasJson(executar('gh', ['api', '-X', 'GET', `repos/${repo}/issues`, '-f', `labels=${ROTULO_TRAVA}`, '-f', `state=${estado}`,
    '-f', 'per_page=100', '--paginate', '--jq', '.[] | @json']));
const erro = (m) => console.log(`::error::${m}`);

function abrir(env) {
  const { VERSAO: versao, SHA: sha, GITHUB_REPOSITORY: repo } = env;
  if (!VERSAO_LIBERAR.test(String(versao || '')) || !SHA_COMPLETO.test(String(sha || ''))) return erro('VERSAO ou SHA inválidos'), 2;
  const aberta = issuesDaTrava(repo, 'open').find((i) => !i.pull_request && i.title === tituloDaIssue(versao));
  if (aberta) return erro(`a issue #${aberta.number} "${aberta.title}" já está aberta: aprove ou feche antes de liberar de novo`), 1;

  const anterior = executar('git', ['tag', '--list', 'v*', '--merged', sha, '--sort=-version:refname'])
    .split('\n').map((t) => t.trim()).find((t) => t && t !== versao) || '';
  const commits = executar('git', ['log', '--format=%H%x09%s', anterior ? `${anterior}..${sha}` : sha])
    .split('\n').filter(Boolean).map((l) => ({ sha: l.slice(0, 40), assunto: l.slice(41) }));
  const run = `${env.GITHUB_SERVER_URL}/${repo}/actions/runs/${env.GITHUB_RUN_ID}`;
  const arquivo = join(mkdtempSync(join(env.RUNNER_TEMP || tmpdir(), 'trava-')), 'corpo.md');
  writeFileSync(arquivo, corpoDaIssue({ versao, sha, run, anterior, commits }));

  try {
    executar('gh', ['api', '-X', 'POST', `repos/${repo}/labels`, '-f', `name=${ROTULO_TRAVA}`, '-f', 'color=b60205',
      '-f', 'description=Deploy de produção esperando o "aprovado vX.Y.Z" do dono do produto']);
  } catch {
    // 422: o rótulo já existe
  }
  const url = executar('gh', ['api', '-X', 'POST', `repos/${repo}/issues`, '-f', `title=${tituloDaIssue(versao)}`,
    '-F', `body=@${arquivo}`, '-f', `labels[]=${ROTULO_TRAVA}`, '--jq', '.html_url']).trim();
  console.log(`[trava] ${tituloDaIssue(versao)}: ${url}`);
  if (env.GITHUB_STEP_SUMMARY)
    appendFileSync(env.GITHUB_STEP_SUMMARY, `### ${versao} esperando aprovação\nIssue: ${url}\nPara aprovar, comente na issue: \`aprovado ${versao}\`\n`);
  return 0;
}

function comentario(env) {
  let evento;
  try {
    evento = JSON.parse(readFileSync(env.GITHUB_EVENT_PATH, 'utf8'));
  } catch {
    return erro('GITHUB_EVENT_PATH ilegível'), 2;
  }
  const d = decidirComentario(evento);
  const saida = d.aprovar ? `aprovar=true\nversao=${d.versao}\nsha=${d.sha}\nissue=${d.issue}\n` : 'aprovar=false\n';
  if (env.GITHUB_OUTPUT) appendFileSync(env.GITHUB_OUTPUT, saida);
  console.log(d.aprovar ? `[trava] aprovação de ${d.versao} (${d.sha}) na issue #${d.issue}` : `[trava] ignorado: ${d.motivo}`);
  return 0;
}

function publicar(env) {
  const { VERSAO: versao, SHA: sha, GITHUB_REPOSITORY: repo } = env;
  let issues;
  try {
    issues = issuesDaTrava(repo, 'all');
  } catch (e) {
    return erro(`não consegui consultar as issues de trava (${String(e.message).split('\n')[0]})`), 1;
  }
  const comentariosDe = (n) =>
    linhasJson(executar('gh', ['api', '-X', 'GET', `repos/${repo}/issues/${n}/comments`, '-f', 'per_page=100', '--paginate', '--jq', '.[] | @json']));
  let e;
  try {
    e = erroDaTrava({ versao, sha, issues, comentariosDe });
  } catch (x) {
    e = `não consegui ler os comentários da issue (${String(x.message).split('\n')[0]})`;
  }
  if (e) return erro(e), 1;
  console.log(`[trava] ${versao} → ${sha}: issue de aprovação conferida`);
  return 0;
}

const MODOS = { abrir, comentario, publicar };

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const modo = MODOS[process.argv[2]];
  if (!modo) {
    console.error('uso: node scripts/ci/producao-trava.mjs abrir|comentario|publicar');
    process.exitCode = 2;
  } else process.exitCode = modo(process.env);
}
